#!/usr/bin/env python3
"""Generate a deterministic C++17 translation unit using GCC 15 #embed.

No runtime extraction: each frontend asset becomes a read-only byte array.
The generated source is a build artifact, not tracked in Git.
"""
import argparse
import hashlib
import json
from pathlib import Path

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".json": "application/json",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".woff2": "font/woff2",
    ".ico": "image/x-icon",
    ".txt": "text/plain; charset=utf-8",
}


def generate(input_dir: Path, output: Path) -> int:
    input_dir = input_dir.resolve(strict=True)
    if not input_dir.is_dir():
        raise ValueError("Asset input must be a directory")
    entries = []
    for file in sorted(input_dir.rglob("*")):
        if file.is_symlink():
            raise ValueError(f"Refusing symlink in web/dist: {file}")
        if not file.is_file():
            continue
        rel = file.relative_to(input_dir).as_posix()
        if '"' in rel or "\\" in rel or "\n" in rel or "\r" in rel:
            raise ValueError(f"Unsupported asset filename: {rel}")
        content = file.read_bytes()
        if len(content) > 16 * 1024 * 1024:
            raise ValueError(f"Single asset too large (>16MiB): {rel}")
        digest = hashlib.sha256(content).hexdigest()
        entries.append((rel, file, len(content), MIME.get(file.suffix.lower(), "application/octet-stream"), '"' + digest[:24] + '"'))
    if not any(rel == "index.html" for rel, *_ in entries):
        raise ValueError("web/dist/index.html missing; build frontend first")
    lines = [
        "// GENERATED by tools/gen_embed.py. Do not edit.",
        '#include "web/embedded_assets.hpp"',
        "#include <algorithm>",
        "#include <iterator>",
        "#include <string_view>",
        "namespace edgedesk { namespace {",
    ]
    for idx, (rel, file, size, mime, etag) in enumerate(entries):
        # GCC 15 supports suffix(,) for C/C++ #embed. Adding the trailing zero
        # makes even empty files valid byte arrays; sizeof(...)-1 is real size.
        path_literal = json.dumps(str(file), ensure_ascii=True)
        lines.extend([
            f"alignas(8) const unsigned char kData{idx}[] = {{",
            f"#embed {path_literal} suffix(,)",
            "0",
            "};",
        ])
    lines.append("const EmbeddedAsset kAssets[] = {")
    for idx, (rel, file, size, mime, etag) in enumerate(entries):
        lines.append(
            f"    {{{json.dumps('/'+rel)}, kData{idx}, sizeof(kData{idx})-1, {json.dumps(mime)}, {json.dumps(etag)}}},"
        )
    lines.extend([
        "};",
        "} // namespace",
        "const EmbeddedAsset* find_embedded_asset(std::string_view path) {",
        "    const auto begin = std::begin(kAssets);",
        "    const auto end = std::end(kAssets);",
        "    const auto it = std::lower_bound(begin, end, path, [](const EmbeddedAsset& a, std::string_view b) {",
        "        return std::string_view(a.path) < b;",
        "    });",
        "    if (it != end && std::string_view(it->path) == path) return it;",
        "    return nullptr;",
        "}",
        "} // namespace edgedesk",
        "",
    ])
    rendered = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    # Avoid unnecessary relinking when byte-for-byte identical.
    if not output.exists() or output.read_text(encoding="utf-8") != rendered:
        output.write_text(rendered, encoding="utf-8")
    return len(entries)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    count = generate(args.input, args.output)
    print(f"Embedded registry: {count} assets -> {args.output}")


if __name__ == "__main__":
    main()
